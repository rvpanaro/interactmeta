test_that("package datasets are documented and accessible", {
  items <- utils::data(package = "interactmeta")$results[, "Item"]
  expect_true(all(c("edss", "age", "il6", "steroids", "respire_age", "respire_sex") %in% items))

  expect_s3_class(edss, "data.frame")
  expect_gt(nrow(edss), 0L)
  expect_true(all(c("yi", "vi", "trial", "subgroup") %in% names(edss)))
  expect_true("trial" %in% names(age))
  expect_false(any(c("study", "study.acronym") %in% names(edss)))
  expect_false("endpoint" %in% names(edss))
  expect_equal(names(edss), c("trial", "subgroup", "n", "treatment", "yi", "vi"))
  expect_equal(names(age), c("trial", "subgroup", "n", "treatment", "yi", "vi"))
  expect_equal(levels(edss$subgroup), c("Lower", "Higher"))
  expect_equal(sort(unique(as.character(edss$subgroup))), c("Higher", "Lower"))
  expect_false("COP1 PILOT" %in% edss$trial)
  expect_true("CONFIRM" %in% edss$trial)
  expect_true(all(c("CONFIRM-B", "CONFIRM-C") %in% age$trial))
  expect_equal(length(unique(edss$trial)), 6L)
  expect_equal(length(unique(age$trial)), 7L)
  expect_false(any(c("ifrac", "ifrac2") %in% names(edss)))
  expect_false(any(c("ifrac", "ifrac2", "subgroup12", "esti", "se", "contrast_yi", "contrast_vi") %in% names(age)))
  expect_true(all(c("yi", "vi") %in% names(age)))
  expect_equal(names(il6), c("trial", "subgroup", "n", "treat.events", "treat.total", "cont.events", "cont.total"))
  expect_false("corticosteroid" %in% names(il6))
  expect_equal(names(steroids), c("trial", "subgroup", "treatment", "n", "treat.events", "treat.total", "cont.events", "cont.total"))
  expect_false(any(c("drug", "ventilation") %in% names(steroids)))
  expect_equal(il6$n, il6$treat.total + il6$cont.total)
  expect_equal(steroids$n, steroids$treat.total + steroids$cont.total)
})
